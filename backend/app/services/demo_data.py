def _lerp(bounds: tuple[float, float], position: float) -> float:
    """Interpolate a value between the two ends of a numeric range."""
    low, high = bounds
    return round(low + (high - low) * position, 4)


def _features(index: int, cluster: dict[str, Any], count: int) -> dict[str, float]:
    """Build the audio-feature vector for one catalog entry."""
    position = index / max(1, count - 1)
    return {
        "danceability": _lerp(cluster["danceability"], position),
        "energy": _lerp(cluster["energy"], position),
        "valence": _lerp(cluster["valence"], position),
        "acousticness": _lerp(cluster["acousticness"], position),
        "instrumentalness": _lerp(cluster["instrumentalness"], position),
        "tempo": _lerp(cluster["tempo"], position),
    }


def _build_catalog() -> tuple[list[dict[str, Any]], dict[str, dict[str, float]]]:
    """Create the demo saved-tracks payload and its feature lookup."""
    items: list[dict[str, Any]] = []
    features: dict[str, dict[str, float]] = {}
    for cluster_index, cluster in enumerate(_CLUSTERS):
        tracks = cluster["tracks"]
        count = cluster.get("count", len(tracks))
        for offset in range(count):
            title, artist = tracks[offset % len(tracks)]
            album_tag = f"{cluster['album']} Essentials"
            track_id = f"{cluster['album'].lower().replace(' ', '-')}-{offset:03d}"
            items.append(
                {
                    "added_at": f"2026-0{1 + offset % 9}-01T08:00:00Z",
                    "track": {
                        "id": track_id,
                        "name": title,
                        "type": "track",
                        "artists": [{"name": artist}],
                        "album": {"name": album_tag},
                        "duration_ms": 180_000 + (offset % 7) * 11_000,
                    },
                }
            )
            features[track_id] = _features(offset, cluster, count)
    return items, features


DEMO_TRACKS, DEMO_FEATURES = _build_catalog()


def saved_tracks() -> list[dict[str, Any]]:
    """Return the demo library in the shape the sync endpoint expects."""
    return DEMO_TRACKS


def features_for(track_ids: list[str]) -> dict[str, dict[str, float]]:
    """Return demo features for the requested track IDs."""
    return {track_id: DEMO_FEATURES[track_id] for track_id in track_ids if track_id in DEMO_FEATURES}


def plan_for_prompt(prompt: str) -> dict[str, Any]:
    """Map a prompt to a playlist plan using keyword presets."""
    lowered = prompt.lower()
    for keywords, name, description, filters in _PRESETS:
        if any(keyword in lowered for keyword in keywords):
            return {"name": name, "description": description, **filters}
    return {
        "name": f"Vibe: {prompt.strip()[:60]}",
        "description": f"Playlist demo dari prompt: {prompt.strip()[:200]}",
    }
